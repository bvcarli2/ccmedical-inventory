-- PostgreSQL employee identity for opt-in secured local staging.
CREATE TABLE IF NOT EXISTS employee_users (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 email TEXT NOT NULL,
 password_hash TEXT NOT NULL,
 role TEXT NOT NULL CHECK (role IN ('admin','employee','viewer')),
 active BOOLEAN NOT NULL DEFAULT TRUE,
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE UNIQUE INDEX IF NOT EXISTS employee_users_email_ci ON employee_users (LOWER(email));

CREATE TABLE IF NOT EXISTS employee_login_attempts (
 email TEXT PRIMARY KEY,
 failures INTEGER NOT NULL DEFAULT 0,
 last_failure TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 blocked_until TIMESTAMPTZ
);

CREATE TABLE IF NOT EXISTS repair_attachments (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 repair_id BIGINT NOT NULL REFERENCES customer_repairs(id),
 stored_name TEXT NOT NULL UNIQUE,
 original_name TEXT NOT NULL,
 mime_type TEXT NOT NULL CHECK (mime_type IN ('image/jpeg','image/png','application/pdf')),
 byte_count INTEGER NOT NULL CHECK (byte_count BETWEEN 1 AND 5242880),
 sha256 TEXT NOT NULL,
 uploaded_by BIGINT NOT NULL REFERENCES employee_users(id),
 uploaded_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_repair_attachments_repair ON repair_attachments(repair_id);

CREATE TABLE IF NOT EXISTS activity_log (id BIGSERIAL PRIMARY KEY, employee_id BIGINT REFERENCES employee_users(id), action TEXT NOT NULL, entity_type TEXT NOT NULL, entity_id TEXT NOT NULL, detail TEXT NOT NULL DEFAULT '', created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP);

CREATE TABLE IF NOT EXISTS employee_login_ip_attempts (ip_address TEXT PRIMARY KEY, failures INTEGER NOT NULL DEFAULT 0, last_failure TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP, blocked_until TIMESTAMPTZ);
