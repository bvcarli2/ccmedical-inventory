-- Product database schema for isolated PostgreSQL staging.
-- Existing SQLite product data must be migrated separately; this is not an import.
CREATE TABLE products (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 category TEXT NOT NULL, manufacturer TEXT, model TEXT NOT NULL,
 display_name TEXT NOT NULL, short_description TEXT, technical_specs TEXT,
 description_source TEXT, spec_source TEXT, review_notes TEXT,
 review_status TEXT NOT NULL DEFAULT 'Pending Review',
 active INTEGER NOT NULL DEFAULT 1, created_at TEXT DEFAULT CURRENT_TIMESTAMP,
 UNIQUE(category,manufacturer,model)
);
CREATE TABLE product_part_numbers (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 product_id BIGINT NOT NULL REFERENCES products(id),
 part_number TEXT NOT NULL, source_url TEXT,
 verification TEXT NOT NULL DEFAULT 'Pending Verification',
 active INTEGER NOT NULL DEFAULT 1,
 UNIQUE(product_id,part_number)
);
CREATE TABLE product_requests (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 category TEXT, manufacturer TEXT, model TEXT, part_number TEXT,
 notes TEXT, request_type TEXT DEFAULT 'New Product',
 status TEXT DEFAULT 'Pending', created_at TEXT DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE product_audit (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 product_id BIGINT REFERENCES products(id), action TEXT, old_value TEXT,
 new_value TEXT, actor TEXT, created_at TEXT DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE product_compatibility (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 probe_id BIGINT NOT NULL REFERENCES products(id),
 system_id BIGINT NOT NULL REFERENCES products(id),
 source_url TEXT, UNIQUE(probe_id,system_id)
);
CREATE TABLE product_imports (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 filename TEXT, imported_at TEXT DEFAULT CURRENT_TIMESTAMP,
 added INTEGER, skipped INTEGER
);
CREATE TABLE product_manufacturers (name TEXT PRIMARY KEY, active INTEGER DEFAULT 1);
CREATE TABLE product_categories (code TEXT PRIMARY KEY,label TEXT NOT NULL,active INTEGER DEFAULT 1);
