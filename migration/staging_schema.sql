-- Staging schema for inventory and repairs only. Never apply to production.
-- Run only against an empty, disposable PostgreSQL database.
CREATE TABLE inventory_id_sequence (
 seq BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 prefix TEXT NOT NULL,
 generated_id TEXT UNIQUE,
 created_at TEXT NOT NULL
);
CREATE TABLE receiving_batches (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 created_at TEXT NOT NULL,
 item_count INTEGER NOT NULL
);
CREATE TABLE units (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 source_sheet TEXT, source_row INTEGER, manufacturer TEXT,
 product_raw TEXT, product_key TEXT, serial TEXT, cost DOUBLE PRECISION,
 dom TEXT, notes TEXT, location_raw TEXT, physical_location TEXT,
 status TEXT, condition TEXT, review TEXT,
 inventory_code TEXT UNIQUE, supplier TEXT, received_date TEXT,
 entry_batch_id BIGINT REFERENCES receiving_batches(id),
 UNIQUE(source_sheet,source_row)
);
CREATE TABLE movements (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 unit_id BIGINT REFERENCES units(id), old_location TEXT,
 new_location TEXT, created_at TEXT DEFAULT CURRENT_TIMESTAMP, note TEXT
);
CREATE TABLE repair_orders (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 unit_id BIGINT REFERENCES units(id), repair_type TEXT,
 status TEXT DEFAULT 'Open', notes TEXT,
 created_at TEXT DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE core_items (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 inventory_code TEXT NOT NULL UNIQUE, manufacturer TEXT,
 product_raw TEXT NOT NULL, serial TEXT, location TEXT, supplier TEXT,
 original_cost DOUBLE PRECISION NOT NULL DEFAULT 0,
 stage TEXT NOT NULL DEFAULT 'Needs Repair', notes TEXT,
 qc_result TEXT, qc_technician TEXT, qc_date TEXT, qc_notes TEXT,
 converted_unit_id BIGINT REFERENCES units(id), created_at TEXT NOT NULL
);
CREATE TABLE core_transactions (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 core_id BIGINT NOT NULL REFERENCES core_items(id),
 performed_at TEXT NOT NULL, technician TEXT, description TEXT NOT NULL,
 labor_method TEXT NOT NULL DEFAULT 'manual',
 labor_hours DOUBLE PRECISION NOT NULL DEFAULT 0,
 labor_rate DOUBLE PRECISION NOT NULL DEFAULT 0,
 labor_cost DOUBLE PRECISION NOT NULL DEFAULT 0,
 parts_cost DOUBLE PRECISION NOT NULL DEFAULT 0,
 other_cost DOUBLE PRECISION NOT NULL DEFAULT 0
);
CREATE TABLE customer_repairs (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 rma TEXT NOT NULL, customer TEXT NOT NULL, manufacturer TEXT, model TEXT,
 part_number TEXT, serial TEXT, location TEXT, received_date TEXT NOT NULL,
 technician TEXT, notes TEXT, stage TEXT NOT NULL DEFAULT 'Open Repairs',
 stage_started_at TEXT NOT NULL, created_at TEXT NOT NULL,
 completed_at TEXT, updated_at TEXT NOT NULL,
 inventory_code TEXT UNIQUE
);
CREATE UNIQUE INDEX customer_repairs_rma_ci ON customer_repairs (lower(rma));
CREATE TABLE customer_repair_history (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 repair_id BIGINT NOT NULL REFERENCES customer_repairs(id),
 old_stage TEXT, new_stage TEXT NOT NULL,
 changed_at TEXT NOT NULL, note TEXT
);
CREATE INDEX idx_repair_history_repair ON customer_repair_history(repair_id);

CREATE TABLE IF NOT EXISTS activity_log (id BIGSERIAL PRIMARY KEY, employee_id BIGINT, action TEXT NOT NULL, entity_type TEXT NOT NULL, entity_id TEXT NOT NULL, detail TEXT NOT NULL DEFAULT '', created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP);
